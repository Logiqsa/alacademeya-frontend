import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const source = new URL("../dist/index.html", import.meta.url);
const destinationDirectory = new URL("../server/generated/", import.meta.url);
const destination = new URL("spa-shell.js", destinationDirectory);
const shell = await readFile(source, "utf8");
const assets = await readdir(new URL("../dist/assets/", import.meta.url));
const heroFile = assets.find((name) => /^small dashbord-[\w-]+\.svg$/.test(name));
if (!heroFile) throw new Error("Missing built landing hero image");
const heroPreloadHref = `/assets/${encodeURIComponent(heroFile)}`;
const heroPreload = `<link rel="preload" as="image" href="${heroPreloadHref}" fetchpriority="high" />`;

await mkdir(destinationDirectory, { recursive: true });
await writeFile(destination, `// Generated by scripts/embed-spa-shell.js; do not edit.\nexport const heroPreloadHref = ${JSON.stringify(heroPreloadHref)};\nexport default ${JSON.stringify(shell)};\n`);
// Vercel serves the static index for '/', so preload there as well. Other SPA routes
// use the unmodified generated shell and do not download the landing image.
await writeFile(source, shell.replace("</head>", `    ${heroPreload}\n  </head>`));
