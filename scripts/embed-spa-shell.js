import { mkdir, readFile, writeFile } from "node:fs/promises";

const source = new URL("../dist/index.html", import.meta.url);
const destinationDirectory = new URL("../server/generated/", import.meta.url);
const destination = new URL("spa-shell.js", destinationDirectory);
const shell = await readFile(source, "utf8");

await mkdir(destinationDirectory, { recursive: true });
await writeFile(destination, `// Generated by scripts/embed-spa-shell.js; do not edit.\nexport default ${JSON.stringify(shell)};\n`);

